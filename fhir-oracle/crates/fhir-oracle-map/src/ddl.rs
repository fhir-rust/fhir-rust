#[cfg(test)]
mod oracle_bounds {
    use super::*;

    /// Every `VARCHAR2` bound this emitter declares must fit the measured
    /// ceiling, in **bytes** — the trap `M14.23d` records, where a `CHAR`
    /// bound reads as characters and is enforced as bytes.
    ///
    /// Mutation-verified (`T11.10`): widening `TextC` to `VARCHAR2(1001 CHAR)`
    /// fails this, which is the point — 1001 × 4 exceeds 4000 and Oracle would
    /// refuse the `CREATE TABLE` with `ORA-00910`.
    #[test]
    fn declared_varchar2_bounds_fit_the_measured_ceiling() {
        for ty in [ColTy::Numeric, ColTy::TextC, ColTy::TextIdx] {
            let sql = col_sql(ty);
            let Some(rest) = sql.strip_prefix("VARCHAR2(") else {
                continue;
            };
            let chars: usize = rest
                .split_whitespace()
                .next()
                .expect("a bound")
                .parse()
                .expect("numeric bound");
            assert!(
                chars <= MAX_VARCHAR2_CHARS,
                "{ty:?} declares VARCHAR2({chars} CHAR) = {} bytes, over the \
                 measured {MAX_VARCHAR2_BYTES}-byte ceiling",
                chars * BYTES_PER_CHAR
            );
        }
    }

    /// `Text` must not be bounded at all: a FHIR string has no length bound,
    /// and binding it to `VARCHAR2` would refuse long values with `ORA-12899`
    /// rather than store them, which `R4.2` forbids.
    #[test]
    fn unbounded_text_is_a_clob() {
        assert_eq!(col_sql(ColTy::Text), "CLOB");
        assert_eq!(col_sql(ColTy::Jsonb), "CLOB");
    }

    /// `M14.23e`: the CHECK cannot be in the type string, so it must not be.
    #[test]
    fn bool_carries_no_inline_check() {
        let sql = col_sql(ColTy::Bool);
        assert_eq!(sql, "NUMBER(1)");
        assert!(
            !sql.contains("CHECK"),
            "an inline CHECK fails with ORA-02438; create_table owns it"
        );
    }
}
